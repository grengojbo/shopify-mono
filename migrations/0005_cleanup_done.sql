-- Чистка замовлень-привидів для інвойсів, які померли самі (`failure`,
-- `expired`): cron має один раз перевірити, чи треба скасувати замовлення,
-- і більше до інвойсу не повертатись. Тут — час цієї перевірки.
--
-- Наявні завершені інвойси позначаються як уже перевірені (0): інакше перший
-- прогін після деплою пройшовся б по всій історії і скасував старі неоплачені
-- замовлення, про які оператор міг давно домовитись окремо. Активні інвойси
-- лишаються NULL — якщо вони помруть уже після деплою, чистка їх підхопить.

ALTER TABLE invoices ADD COLUMN cleanup_done_at INTEGER;

UPDATE invoices SET cleanup_done_at = 0 WHERE status IN ('failure', 'expired');
