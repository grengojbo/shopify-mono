-- Ідемпотентність вебхуків на рівні схеми. Досі її тримала лише перевірка
-- SELECT → INSERT у коді, не атомарна: два одночасні вебхуки з тим самим
-- invoiceId+status обидва бачили «ще не оброблено» і обидва писали в журнал.
-- Індекс заодно прискорює сам пошук, який робиться на кожен вебхук.

CREATE UNIQUE INDEX idx_webhook_log_invoice_status
  ON webhook_log(invoice_id, status);
